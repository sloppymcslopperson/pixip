const CLI = fileURLToPath(new URL("../bin/pixip.ts", import.meta.url));

function ok(stdout = ""): CommandResult {
	return { code: 0, stdout, stderr: "" };
}

function fail(code = 1, stderr = ""): CommandResult {
	return { code, stdout: "", stderr };
}

interface FakeRunner extends CommandRunner {
	calls: string[];
}

function fakeRunner(handler: (command: string, args: string[]) => CommandResult | undefined): FakeRunner {
	const calls: string[] = [];
	return {
		calls,
		run(command, args) {
			calls.push([command, ...args].join(" "));
			return Promise.resolve(handler(command, args) ?? ok());
		},
	};
}

function account(name: string, home: string) {
	return { name, uid: 1000, gid: 1000, home, shell: "/bin/bash" };
}

function target(name: string, home: string): ServiceTarget {
	return { account: account(name, home), group: name, defaulted: false };
}

function unitFor(root: string, scope: "user" | "system", user = "tester") {
	const home = join(root, "home");
	const dataDir = join(home, "pixip_data");
	const workingDirectory = join(home, "dev");
	const unit = generateUnit({
		scope,
		user,
		group: user,
		home,
		dataDir,
		workingDirectory,
		nodePath: "/usr/bin/node",
		entryPath: "/repo/bin/pixip.ts",
		serveArgs: ["--host", "127.0.0.1", "--port", "8137", "--data-dir", dataDir, "--pi", "/usr/bin/pi"],
		pathEnv: servicePathEnv("/usr/bin/node", "/usr/bin/pi"),
	});
	return { home, dataDir, workingDirectory, unit };
}

function runCli(
	args: string[],
	env: Record<string, string> = {},
): Promise<{ code: number; stdout: string; stderr: string }> {
	return new Promise((resolve) => {
		execFile(
			process.execPath,
			[CLI, ...args],
			{ env: { ...process.env, ...env }, timeout: 20_000 },
			(error, stdout, stderr) => {
				const code = error ? (typeof error.code === "number" ? error.code : 1) : 0;
				resolve({ code, stdout, stderr });
			},
		);
	});
}

after(async () => {
	for (const dir of testRoots()) {
		const state = await readDaemonState(dir);
		if (state && pidAlive(state.pid)) {
			try {
				process.kill(state.pid, "SIGKILL");
			} catch {
				// already gone
			}
		}
	}
	await cleanupRoots();
});

describe("systemd unit generation", () => {
	it("writes a user unit with absolute paths, metadata and linger target", () => {
		const root = "/tmp/pixip-unit";
		const { dataDir, unit } = unitFor(root, "user");
		assert.match(unit, /^# Generated by pixip service install/);
		assert.match(unit, /# pixip-scope=user/);
		assert.match(unit, new RegExp(`# pixip-data-dir=${dataDir}`));
		assert.match(unit, /ExecStart="\/usr\/bin\/node" "\/repo\/bin\/pixip.ts" "serve"/);
		assert.match(unit, /WorkingDirectory="\/tmp\/pixip-unit\/home\/dev"/);
		assert.match(unit, /Environment="HOME=\/tmp\/pixip-unit\/home"/);
		assert.match(unit, /Environment="PATH=.*\/usr\/bin/);
		assert.match(unit, /Environment=PIXIP_SERVICE=user/);
		assert.match(unit, /StandardOutput=append:"\/tmp\/pixip-unit\/home\/pixip_data\/pixip\.log"/);
		assert.match(unit, /WantedBy=default\.target/);
		assert.doesNotMatch(unit, /^User=/m);
	});

	it("writes a system unit with User/Group and multi-user target", () => {
		const { unit } = unitFor("/tmp/pixip-unit", "system", "pixip");
		assert.match(unit, /^User=pixip$/m);
		assert.match(unit, /^Group=pixip$/m);
		assert.match(unit, /WantedBy=multi-user\.target/);
	});

	it("quotes percent and dollar specifiers and round-trips metadata", () => {
		const unit = generateUnit({
			scope: "user",
			user: "a",
			group: "a",
			home: "/home/a%$",
			dataDir: "/data/a%$",
			workingDirectory: "/home/a%$/dev",
			nodePath: "/usr/bin/node",
			entryPath: "/repo/bin/pixip.ts",
			serveArgs: ["--title-model", "p/id%$"],
			pathEnv: "/usr/bin",
		});
		assert.match(unit, /%%\$\$/);
		const metadata = parseUnitMetadata(unit);
		assert.equal(metadata.scope, "user");
		assert.equal(metadata.dataDir, "/data/a%$");
		assert.equal(metadata.workingDirectory, "/home/a%$/dev");
	});

	it("uses standard unit paths", () => {
		assert.equal(userServiceUnitPath("/home/tester"), "/home/tester/.config/systemd/user/pixip.service");
		assert.equal(systemServiceUnitPath(), "/etc/systemd/system/pixip.service");
		assert.deepEqual(systemctlArgs("user", "restart", "pixip.service"), ["--user", "restart", "pixip.service"]);
		assert.deepEqual(systemctlArgs("system", "restart", "pixip.service"), ["restart", "pixip.service"]);
	});
});

describe("service account resolution", () => {
	it("rejects an explicit --user that does not exist", async () => {
		const runner = fakeRunner((command) => (command === "getent" ? fail(2) : undefined));
		await assert.rejects(resolveServiceTarget({ requestedUser: "alice", runner }), /does not exist/);
	});

	it("resolves --user self through SUDO_USER", async () => {
		const runner = fakeRunner((command, args) => {
			if (command === "getent" && args[1] === "alice") {
				return ok("alice:x:1001:1001::/home/alice:/bin/bash\n");
			}
			if (command === "id" && args[0] === "-gn") return ok("alice\n");
			return undefined;
		});
		const target = await resolveServiceTarget({
			requestedUser: "self",
			runner,
			env: { SUDO_USER: "alice" },
		});
		assert.equal(target.account.name, "alice");
		assert.equal(target.group, "alice");
		assert.equal(target.defaulted, false);
	});

	it("creates the default pixip user after confirmation", async () => {
		let created = false;
		const runner = fakeRunner((command, args) => {
			if (command === "getent" && args[1] === "pixip") {
				return created ? ok("pixip:x:999:999::/home/pixip:/bin/bash\n") : fail(2);
			}
			if (command === "useradd") {
				created = true;
				return ok();
			}
			if (command === "id" && args[0] === "-gn") return ok("pixip\n");
			return undefined;
		});
		const target = await resolveServiceTarget({
			runner,
			confirmDefault: () => Promise.resolve(true),
		});
		assert.equal(target.account.name, "pixip");
		assert.equal(target.defaulted, true);
		assert.ok(runner.calls.some((call) => call.startsWith("useradd --system --create-home --shell /bin/bash")));
	});

	it("does not create pixip when confirmation is refused", async () => {
		const runner = fakeRunner(() => fail(2));
		await assert.rejects(resolveServiceTarget({ runner, confirmDefault: () => Promise.resolve(false) }), /cancelled/);
		assert.equal(runner.calls.length, 0);
	});
});

describe("service install/status/uninstall", () => {
	it("installs, refuses a second install, and replaces explicitly", async () => {
		const root = await tempRoot("pixip-service-");
		const unitPath = join(root, "pixip.service");
		const { dataDir, workingDirectory, unit } = unitFor(root, "user");
		const runner = fakeRunner(() => ok());
		const input = {
			scope: "user" as const,
			unitPath,
			unit,
			dataDir,
			workingDirectory,
			target: target("tester", join(root, "home")),
			runner,
			replace: false,
		};
		await installService(input);
		assert.equal(await serviceUnitExists(unitPath), true);
		assert.equal((await stat(dataDir)).isDirectory(), true);
		assert.ok(runner.calls.includes("systemctl --user daemon-reload"));
		assert.ok(runner.calls.includes("systemctl --user enable pixip.service"));
		assert.ok(runner.calls.includes("systemctl --user restart pixip.service"));
		assert.ok(runner.calls.some((call) => call.startsWith("loginctl enable-linger tester")));
		await assert.rejects(installService(input), /already exists/);
		await installService({ ...input, replace: true, unit: `${unit}# replaced\n` });
		assert.match(await readFile(unitPath, "utf8"), /# replaced/);
	});

	it("reports linger failure with the exact sudo command", async () => {
		const root = await tempRoot("pixip-service-");
		const { dataDir, workingDirectory, unit } = unitFor(root, "user");
		const runner = fakeRunner((command) => (command === "loginctl" ? fail(1, "no bus") : undefined));
		const result = await installService({
			scope: "user",
			unitPath: join(root, "pixip.service"),
			unit,
			dataDir,
			workingDirectory,
			target: target("tester", join(root, "home")),
			runner,
			replace: false,
		});
		assert.equal(result.lingerCommand, "sudo loginctl enable-linger tester");
	});

	it("reports installed/enabled/active and the recorded data dir", async () => {
		const root = await tempRoot("pixip-service-");
		const unitPath = join(root, "pixip.service");
		const { dataDir, workingDirectory, unit } = unitFor(root, "user");
		await installService({
			scope: "user",
			unitPath,
			unit,
			dataDir,
			workingDirectory,
			target: target("tester", join(root, "home")),
			runner: fakeRunner(() => ok()),
			replace: false,
		});
		const runner = fakeRunner((command, args) => {
			if (command !== "systemctl") return undefined;
			if (args.includes("is-enabled")) return ok("enabled\n");
			if (args.includes("is-active")) return ok("active\n");
			return undefined;
		});
		const status = await readServiceStatus({
			scope: "user",
			unitPath,
			fallbackDataDir: "/wrong",
			runner,
		});
		assert.equal(status.installed, true);
		assert.equal(status.enabled, "enabled");
		assert.equal(status.active, "active");
		assert.equal(status.dataDir, dataDir);
		assert.equal(status.metadata.user, "tester");
	});

	it("uninstalls idempotently and only deletes data on request", async () => {
		const root = await tempRoot("pixip-service-");
		const unitPath = join(root, "pixip.service");
		const { dataDir, workingDirectory, unit } = unitFor(root, "user");
		const runner = fakeRunner(() => ok());
		await installService({
			scope: "user",
			unitPath,
			unit,
			dataDir,
			workingDirectory,
			target: target("tester", join(root, "home")),
			runner,
			replace: false,
		});
		const first = await uninstallService({ scope: "user", unitPath, runner, deleteData: false });
		assert.equal(first.installed, true);
		assert.equal(first.dataRemoved, false);
		assert.equal(await serviceUnitExists(unitPath), false);
		assert.equal((await stat(dataDir)).isDirectory(), true);
		const second = await uninstallService({ scope: "user", unitPath, runner, deleteData: false });
		assert.equal(second.installed, false);

		await installService({
			scope: "user",
			unitPath,
			unit,
			dataDir,
			workingDirectory,
			target: target("tester", join(root, "home")),
			runner,
			replace: false,
		});
		const purged = await uninstallService({ scope: "user", unitPath, runner, deleteData: true });
		assert.equal(purged.dataRemoved, true);
		await assert.rejects(stat(dataDir), /ENOENT/);
	});

	it("refuses to delete an unsafe data dir", async () => {
		const root = await tempRoot("pixip-service-");
		const unitPath = join(root, "pixip.service");
		const unit = generateUnit({
			scope: "user",
			user: "tester",
			group: "tester",
			home: "/",
			dataDir: "/",
			workingDirectory: "/",
			nodePath: "/usr/bin/node",
			entryPath: "/repo/bin/pixip.ts",
			serveArgs: [],
			pathEnv: "/usr/bin",
		});
		const runner = fakeRunner(() => ok());
		await installService({
			scope: "user",
			unitPath,
			unit,
			dataDir: join(root, "data"),
			workingDirectory: join(root, "work"),
			target: target("tester", root),
			runner,
			replace: false,
		});
		await assert.rejects(
			uninstallService({ scope: "user", unitPath: join(root, "pixip.service"), runner, deleteData: true }),
			/unsafe data dir/,
		);
	});
});

describe("service command helpers", () => {
	it("resolves executables and reports missing ones", async () => {
		assert.equal(await resolveExecutable(process.execPath), process.execPath);
		await assert.rejects(
			resolveExecutable("definitely-not-a-pixip-executable", { PATH: "/nonexistent" }),
			/cannot find/,
		);
		await assert.rejects(resolveExecutable("/nonexistent/node"), /not executable/);
	});

	it("copies node when the system service user cannot execute it", async () => {
		const root = await tempRoot("pixip-service-node-");
		const source = join(root, "node");
		const copy = join(root, "system", "node");
		await writeFile(source, "node-binary");
		await chmod(source, 0o700);
		const other = { name: "other", uid: 12345, gid: 12345, home: root, shell: "/bin/bash" };
		assert.equal(await canExecuteAs(source, other), false);
		const copied = await ensureServiceNode({
			nodePath: source,
			scope: "system",
			target: { account: other, group: "other", defaulted: false },
			copyPath: copy,
		});
		assert.equal(copied.copied, true);
		assert.equal(copied.nodePath, copy);
		assert.equal(await readFile(copy, "utf8"), "node-binary");
		assert.equal((await stat(copy)).mode & 0o777, 0o755);

		await chmod(source, 0o755);
		await chmod(root, 0o755);
		assert.equal(await canExecuteAs(source, other), true);
		const reused = await ensureServiceNode({
			nodePath: source,
			scope: "system",
			target: { account: other, group: "other", defaulted: false },
			copyPath: join(root, "unused"),
		});
		assert.equal(reused.copied, false);
		assert.equal(reused.nodePath, source);
	});

	it("detects the systemd marker and MainPID ownership", async () => {
		assert.equal(serviceScopeFromEnv({ PIXIP_SERVICE: "user" }), "user");
		assert.equal(serviceScopeFromEnv({ PIXIP_SERVICE: "system" }), "system");
		assert.equal(serviceScopeFromEnv({ PIXIP_SERVICE: "nope" }), undefined);
		assert.deepEqual(restartDecision({ PIXIP_SERVICE: "user" }), { mode: "systemd", scope: "user" });
		assert.deepEqual(restartDecision({}), { mode: "detached" });

		const runner = fakeRunner((command, args) => {
			if (command === "systemctl" && args.includes("MainPID")) return ok("1234\n");
			return undefined;
		});
		assert.equal(await serviceOwnsPid("user", 1234, runner), true);
		assert.equal(await serviceOwnsPid("user", 9999, runner), false);
	});

	it("prints service help and rejects --user without --system", async () => {
		const help = await runCli(["service"]);
		assert.equal(help.code, 0);
		assert.match(help.stdout, /pixip service <install\|status\|uninstall>/);

		const invalid = await runCli(["service", "install", "--user", "alice"]);
		assert.equal(invalid.code, 1);
		assert.match(invalid.stderr, /--user is only valid with --system/);
	});

	it("lets an agent inside pixip restart through systemctl", async () => {
		const root = await tempRoot("pixip-service-restart-");
		const bin = join(root, "bin");
		const log = join(root, "systemctl.log");
		await mkdir(bin, { recursive: true });
		const systemctl = join(bin, "systemctl");
		await writeFile(
			systemctl,
			`#!/bin/sh
printf '%s\\n' "$*" >> "$SYSTEMCTL_LOG"
if [ "$1" = "--user" ]; then shift; fi
case "$1" in
  restart)
    env -u PIXIP_SERVICE -u PIXIP_SESSION_ID -u PIXIP_INSIDE "$NODE" "$CLI" stop --data-dir "$DATA_DIR" >/dev/null 2>&1 || true
    exec "$NODE" "$CLI" start --data-dir "$DATA_DIR" --port 0 --pi "$PI"
    ;;
  *) exit 0 ;;
esac
`,
		);
		await chmod(systemctl, 0o755);

		const started = await runCli(["start", "--data-dir", root, "--port", "0", "--pi", FIXTURE]);
		assert.equal(started.code, 0, started.stderr);
		const before = await readDaemonState(root);
		assert.ok(before);

		const restarted = await runCli(["restart", "--data-dir", root], {
			PATH: `${bin}:${process.env["PATH"] ?? ""}`,
			PIXIP_SERVICE: "user",
			PIXIP_SESSION_ID: "agent-session",
			SYSTEMCTL_LOG: log,
			NODE: process.execPath,
			CLI,
			DATA_DIR: root,
			PI: FIXTURE,
		});
		assert.equal(restarted.code, 0, restarted.stderr);
		const afterRestart = await readDaemonState(root);
		assert.ok(afterRestart);
		assert.notEqual(afterRestart.pid, before.pid);
		assert.match(await readFile(log, "utf8"), /--user restart pixip\.service/);

		await runCli(["stop", "--data-dir", root]);
	});
});
