/**
 * systemd service support for the CLI.
 *
 * This module is deliberately separate from `daemon.ts`: it builds the unit,
 * resolves the service account, and talks to `systemctl`/`loginctl` through an
 * injected runner, so tests never need a real systemd bus. The CLI keeps the
 * user-facing prompts and output.
 */
import { spawn } from "node:child_process";
import { constants } from "node:fs";
import {
	access,
	chmod,
	chown,
	copyFile,
	mkdir,
	readFile,
	realpath,
	rename,
	rm,
	stat,
	writeFile,
} from "node:fs/promises";
import { homedir } from "node:os";
import { delimiter, dirname, isAbsolute, join, resolve } from "node:path";

export type ServiceScope = "user" | "system";
export type ServiceAction = "install" | "status" | "uninstall";

export const SERVICE_NAME = "pixip";
export const SERVICE_UNIT = `${SERVICE_NAME}.service`;
const GENERATED_MARKER = "# Generated by pixip service install";
const UNIT_METADATA = /^# pixip-(scope|user|data-dir|working-directory)=(.*)$/;

export interface CommandResult {
	code: number;
	stdout: string;
	stderr: string;
}

export interface CommandRunner {
	run(command: string, args: string[], env?: NodeJS.ProcessEnv): Promise<CommandResult>;
}

/** Spawn one command, capturing stdout/stderr; never throws for a non-zero exit. */
export const defaultRunner: CommandRunner = {
	run(command, args, env = process.env) {
		return new Promise((done) => {
			const child = spawn(command, args, { env, stdio: ["ignore", "pipe", "pipe"] });
			let stdout = "";
			let stderr = "";
			child.stdout.setEncoding("utf8");
			child.stderr.setEncoding("utf8");
			child.stdout.on("data", (chunk: string) => {
				stdout += chunk;
			});
			child.stderr.on("data", (chunk: string) => {
				stderr += chunk;
			});
			child.once("error", (error) => {
				done({ code: 127, stdout, stderr: `${stderr}${error.message}\n` });
			});
			child.once("close", (code) => {
				done({ code: code ?? 1, stdout, stderr });
			});
		});
	},
};

export interface ServiceUnitMetadata {
	scope?: ServiceScope;
	user?: string;
	dataDir?: string;
	workingDirectory?: string;
}

export interface ServiceUnitSpec {
	scope: ServiceScope;
	user: string;
	group: string;
	home: string;
	dataDir: string;
	workingDirectory: string;
	nodePath: string;
	entryPath: string;
	serveArgs: string[];
	pathEnv: string;
}

export interface UserAccount {
	name: string;
	uid: number;
	gid: number;
	home: string;
	shell: string;
}

export interface ServiceTarget {
	account: UserAccount;
	group: string;
	/** True when no --user was supplied and the pixip account was chosen. */
	defaulted: boolean;
}

export function userServiceUnitPath(home = homedir()): string {
	return join(home, ".config", "systemd", "user", SERVICE_UNIT);
}

export function systemServiceUnitPath(root = "/"): string {
	return join(root, "etc", "systemd", "system", SERVICE_UNIT);
}

export function systemctlArgs(scope: ServiceScope, ...args: string[]): string[] {
	return scope === "user" ? ["--user", ...args] : args;
}

/** Quote one systemd argument; `%` and `$` are specifiers/expansions in units. */
export function systemdQuote(value: string): string {
	const escaped = value
		.replaceAll("\\", () => "\\\\")
		.replaceAll('"', () => '\\"')
		.replaceAll("%", () => "%%")
		.replaceAll("$", () => "$$");
	return `"${escaped}"`;
}

export function generateUnit(spec: ServiceUnitSpec): string {
	const exec = [spec.nodePath, spec.entryPath, "serve", ...spec.serveArgs].map(systemdQuote).join(" ");
	const lines = [
		`${GENERATED_MARKER}; reinstall with --replace.`,
		`# pixip-scope=${spec.scope}`,
		`# pixip-user=${spec.user}`,
		`# pixip-data-dir=${spec.dataDir}`,
		`# pixip-working-directory=${spec.workingDirectory}`,
		"",
		"[Unit]",
		"Description=pixip (Pi session supervisor)",
		"After=network.target",
		"",
		"[Service]",
		"Type=simple",
		`ExecStart=${exec}`,
		`WorkingDirectory=${systemdQuote(spec.workingDirectory)}`,
		`Environment=${systemdQuote(`HOME=${spec.home}`)}`,
		`Environment=${systemdQuote(`PATH=${spec.pathEnv}`)}`,
		`Environment=PIXIP_SERVICE=${spec.scope}`,
		`StandardOutput=append:${systemdQuote(join(spec.dataDir, "pixip.log"))}`,
		"StandardError=inherit",
		"Restart=on-failure",
		"RestartSec=2",
		"KillSignal=SIGTERM",
		"TimeoutStopSec=20",
	];
	if (spec.scope === "system") lines.push(`User=${spec.user}`, `Group=${spec.group}`);
	lines.push("", "[Install]", `WantedBy=${spec.scope === "user" ? "default.target" : "multi-user.target"}`, "");
	return lines.join("\n");
}

export function isGeneratedUnit(text: string): boolean {
	return text.startsWith(GENERATED_MARKER);
}

export function parseUnitMetadata(text: string): ServiceUnitMetadata {
	const metadata: ServiceUnitMetadata = {};
	for (const line of text.split("\n")) {
		const match = UNIT_METADATA.exec(line);
		if (!match) continue;
		const key = match[1];
		const value = match[2] ?? "";
		if (key === "scope") {
			if (value === "user" || value === "system") metadata.scope = value;
		} else if (key === "user") {
			metadata.user = value;
		} else if (key === "data-dir") {
			metadata.dataDir = value;
		} else if (key === "working-directory") {
			metadata.workingDirectory = value;
		}
	}
	return metadata;
}

/** Resolve an executable name against PATH and require it to be runnable. */
export async function resolveExecutable(name: string, env: NodeJS.ProcessEnv = process.env): Promise<string> {
	if (!name) throw new Error("executable name is empty");
	if (name.includes("/") || name.includes("\\")) {
		const path = resolve(name);
		await requireExecutable(path, name);
		return path;
	}
	for (const directory of (env["PATH"] ?? "").split(delimiter)) {
		if (!directory) continue;
		const candidate = join(directory, name);
		try {
			await access(candidate, constants.X_OK);
			const info = await stat(candidate);
			if (info.isFile()) return candidate;
		} catch {
			// keep searching
		}
	}
	throw new Error(`cannot find ${name} on PATH; pass an absolute --pi path`);
}

async function requireExecutable(path: string, label: string): Promise<void> {
	try {
		await access(path, constants.X_OK);
		const info = await stat(path);
		if (!info.isFile()) throw new Error("not a file");
	} catch (error) {
		throw new Error(`${label} is not executable: ${path} (${(error as Error).message})`);
	}
}

function permissionFor(info: { uid: number; gid: number; mode: number }, account: UserAccount, mask: number): boolean {
	if (account.uid === 0) return mask === 0o1 ? (info.mode & 0o111) !== 0 : true;
	if (info.uid === account.uid) return (info.mode & (mask << 6)) !== 0;
	if (info.gid === account.gid) return (info.mode & (mask << 3)) !== 0;
	return (info.mode & mask) !== 0;
}

/** Can this account traverse to and execute `path` using its own uid/gid? */
export async function canExecuteAs(path: string, account: UserAccount): Promise<boolean> {
	let real: string;
	try {
		real = await realpath(path);
	} catch {
		return false;
	}
	const file = await stat(real).catch(() => undefined);
	if (!file?.isFile() || !permissionFor(file, account, 0o1)) return false;

	const directories: string[] = [];
	let current = dirname(real);
	for (;;) {
		directories.push(current);
		const parent = dirname(current);
		if (parent === current) break;
		current = parent;
	}
	for (const directory of directories) {
		const info = await stat(directory).catch(() => undefined);
		if (!info?.isDirectory() || !permissionFor(info, account, 0o1)) return false;
	}
	return true;
}

/**
 * A system unit runs as another account. If that account cannot execute the
 * installer's node (for example an nvm install under a 0700 home), copy the
 * binary to a system location and point the unit at that copy instead.
 */
export async function ensureServiceNode(input: {
	nodePath: string;
	scope: ServiceScope;
	target?: ServiceTarget;
	copyPath?: string;
}): Promise<{ nodePath: string; copied: boolean }> {
	if (input.scope !== "system" || !input.target) return { nodePath: input.nodePath, copied: false };
	if (await canExecuteAs(input.nodePath, input.target.account)) {
		return { nodePath: input.nodePath, copied: false };
	}
	const destination = input.copyPath ?? join("/usr/local/lib", SERVICE_NAME, "node");
	const directory = dirname(destination);
	await mkdir(directory, { recursive: true, mode: 0o755 });
	await chmod(directory, 0o755);
	await copyFile(input.nodePath, destination);
	await chmod(destination, 0o755);
	return { nodePath: destination, copied: true };
}

export async function readUserAccount(name: string, runner: CommandRunner): Promise<UserAccount | undefined> {
	const result = await runner.run("getent", ["passwd", name]);
	if (result.code !== 0) return undefined;
	const fields = result.stdout.trim().split(":");
	if (fields.length < 7) return undefined;
	const uid = Number(fields[2]);
	const gid = Number(fields[3]);
	if (!Number.isInteger(uid) || !Number.isInteger(gid)) return undefined;
	return {
		name: fields[0] ?? name,
		uid,
		gid,
		home: fields[5] ?? "",
		shell: fields[6] ?? "",
	};
}

export async function primaryGroup(name: string, runner: CommandRunner): Promise<string> {
	const result = await runner.run("id", ["-gn", name]);
	if (result.code !== 0) throw new Error(`cannot resolve the primary group for ${name}: ${result.stderr.trim()}`);
	const group = result.stdout.trim();
	if (!group) throw new Error(`cannot resolve the primary group for ${name}`);
	return group;
}

function currentUserName(env: NodeJS.ProcessEnv): string {
	const sudoUser = env["SUDO_USER"]?.trim();
	if (sudoUser) return sudoUser;
	const user = env["USER"]?.trim();
	if (user) return user;
	return process.env["USER"]?.trim() || "root";
}

/**
 * Pick the account a system unit runs as. `--user self` resolves to SUDO_USER,
 * then the current user. No `--user` defaults to the unprivileged `pixip`
 * account, asking first when a confirmation callback is supplied.
 */
export async function resolveServiceTarget(input: {
	requestedUser?: string;
	runner: CommandRunner;
	env?: NodeJS.ProcessEnv;
	confirmDefault?: () => Promise<boolean>;
}): Promise<ServiceTarget> {
	const env = input.env ?? process.env;
	let name = input.requestedUser?.trim() || undefined;
	const defaulted = name === undefined;
	if (name === "self") name = currentUserName(env);
	if (defaulted) {
		name = SERVICE_NAME;
		if (input.confirmDefault && !(await input.confirmDefault())) {
			throw new Error("service install cancelled; pass --user <name> or --user self");
		}
	}
	let account = name ? await readUserAccount(name, input.runner) : undefined;
	if (!account) {
		if (!defaulted) throw new Error(`user ${name} does not exist; create it first or use --user self`);
		const created = await input.runner.run("useradd", [
			"--system",
			"--create-home",
			"--shell",
			"/bin/bash",
			SERVICE_NAME,
		]);
		if (created.code !== 0) {
			throw new Error(`cannot create the ${SERVICE_NAME} service user: ${created.stderr.trim()}`);
		}
		account = await readUserAccount(SERVICE_NAME, input.runner);
		if (!account) throw new Error(`created ${SERVICE_NAME}, but the account cannot be read back`);
	}
	return { account, group: await primaryGroup(account.name, input.runner), defaulted };
}

export function servicePathEnv(...executables: Array<string | undefined>): string {
	const directories = ["/usr/local/sbin", "/usr/local/bin", "/usr/sbin", "/usr/bin", "/sbin", "/bin"];
	for (const executable of executables) {
		if (!executable) continue;
		const directory = dirname(executable);
		if (!directories.includes(directory)) directories.unshift(directory);
	}
	return directories.join(":");
}

async function ensureDirectory(path: string, target?: ServiceTarget): Promise<void> {
	let existed = true;
	try {
		const info = await stat(path);
		if (!info.isDirectory()) throw new Error(`${path} exists but is not a directory`);
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
		existed = false;
	}
	await mkdir(path, { recursive: true });
	if (!existed && target && process.geteuid?.() === 0) {
		await chown(path, target.account.uid, target.account.gid);
	}
}

async function readExisting(path: string): Promise<string | undefined> {
	try {
		return await readFile(path, "utf8");
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
		throw error;
	}
}

export async function serviceUnitExists(path: string): Promise<boolean> {
	return (await readExisting(path)) !== undefined;
}

async function writeAtomic(path: string, content: string): Promise<void> {
	await mkdir(dirname(path), { recursive: true });
	const temp = `${path}.${process.pid}.tmp`;
	await writeFile(temp, content, { mode: 0o644 });
	await rename(temp, path);
}

async function runChecked(runner: CommandRunner, command: string, args: string[]): Promise<CommandResult> {
	const result = await runner.run(command, args);
	if (result.code !== 0) {
		const detail = (result.stderr || result.stdout).trim();
		throw new Error(`${command} ${args.join(" ")} failed (${result.code})${detail ? `: ${detail}` : ""}`);
	}
	return result;
}

export interface InstallServiceInput {
	scope: ServiceScope;
	unitPath: string;
	unit: string;
	dataDir: string;
	workingDirectory: string;
	target?: ServiceTarget;
	runner: CommandRunner;
	replace: boolean;
}

export interface InstallServiceResult {
	unitPath: string;
	enabled: boolean;
	started: boolean;
	lingerCommand?: string;
}

export async function installService(input: InstallServiceInput): Promise<InstallServiceResult> {
	const existing = await readExisting(input.unitPath);
	if (existing !== undefined && !input.replace) {
		throw new Error(`unit already exists: ${input.unitPath}; rerun with --replace to overwrite it`);
	}
	await ensureDirectory(input.dataDir, input.scope === "system" ? input.target : undefined);
	await ensureDirectory(input.workingDirectory, input.scope === "system" ? input.target : undefined);
	await writeAtomic(input.unitPath, input.unit);
	await runChecked(input.runner, "systemctl", systemctlArgs(input.scope, "daemon-reload"));
	await runChecked(input.runner, "systemctl", systemctlArgs(input.scope, "enable", SERVICE_UNIT));
	await runChecked(input.runner, "systemctl", systemctlArgs(input.scope, "restart", SERVICE_UNIT));

	let lingerCommand: string | undefined;
	if (input.scope === "user" && input.target) {
		const user = input.target.account.name;
		const linger = await input.runner.run("loginctl", ["enable-linger", user]);
		if (linger.code !== 0) lingerCommand = `sudo loginctl enable-linger ${user}`;
	}
	return { unitPath: input.unitPath, enabled: true, started: true, lingerCommand };
}

export interface ServiceStatus {
	scope: ServiceScope;
	unitPath: string;
	installed: boolean;
	enabled: string;
	active: string;
	metadata: ServiceUnitMetadata;
	dataDir: string;
}

export interface ReadServiceStatusInput {
	scope: ServiceScope;
	unitPath: string;
	fallbackDataDir: string;
	runner: CommandRunner;
}

export async function readServiceStatus(input: ReadServiceStatusInput): Promise<ServiceStatus> {
	const text = await readExisting(input.unitPath);
	if (text === undefined) {
		return {
			scope: input.scope,
			unitPath: input.unitPath,
			installed: false,
			enabled: "not installed",
			active: "not installed",
			metadata: {},
			dataDir: input.fallbackDataDir,
		};
	}
	const enabled = await input.runner.run("systemctl", systemctlArgs(input.scope, "is-enabled", SERVICE_UNIT));
	const active = await input.runner.run("systemctl", systemctlArgs(input.scope, "is-active", SERVICE_UNIT));
	const metadata = parseUnitMetadata(text);
	return {
		scope: input.scope,
		unitPath: input.unitPath,
		installed: true,
		enabled: enabled.stdout.trim() || (enabled.code === 0 ? "enabled" : "unknown"),
		active: active.stdout.trim() || (active.code === 0 ? "active" : "unknown"),
		metadata,
		dataDir: metadata.dataDir ?? input.fallbackDataDir,
	};
}

export interface UninstallServiceInput {
	scope: ServiceScope;
	unitPath: string;
	runner: CommandRunner;
	deleteData: boolean;
}

export interface UninstallServiceResult {
	installed: boolean;
	removed: boolean;
	dataRemoved: boolean;
	dataDir?: string;
	warnings: string[];
}

/** Refuse to delete obviously dangerous paths even if a unit comment claims them. */
export function assertSafeDataDir(path: string): string {
	const resolved = resolve(path);
	if (!isAbsolute(path) || resolved === "/" || resolved === resolve(homedir())) {
		throw new Error(`refusing to delete unsafe data dir: ${path}`);
	}
	return resolved;
}

export async function uninstallService(input: UninstallServiceInput): Promise<UninstallServiceResult> {
	const text = await readExisting(input.unitPath);
	if (text === undefined) {
		return { installed: false, removed: false, dataRemoved: false, warnings: [] };
	}
	const metadata = parseUnitMetadata(text);
	const warnings: string[] = [];
	const commands: string[][] = [
		systemctlArgs(input.scope, "stop", SERVICE_UNIT),
		systemctlArgs(input.scope, "disable", SERVICE_UNIT),
		systemctlArgs(input.scope, "daemon-reload"),
	];
	for (const args of commands) {
		const result = await input.runner.run("systemctl", args);
		if (result.code !== 0) warnings.push(`systemctl ${args.join(" ")}: ${(result.stderr || result.stdout).trim()}`);
	}
	await rm(input.unitPath, { force: true });
	let dataRemoved = false;
	let dataDir = metadata.dataDir;
	if (input.deleteData) {
		if (!dataDir) throw new Error("the unit does not record a data dir; refusing to delete data");
		dataDir = assertSafeDataDir(dataDir);
		await rm(dataDir, { recursive: true, force: true });
		dataRemoved = true;
	}
	return { installed: true, removed: true, dataRemoved, dataDir, warnings };
}

export interface InstalledService {
	scope: ServiceScope;
	unitPath: string;
	metadata: ServiceUnitMetadata;
}

/** Find a generated unit whose recorded data dir matches `dataDir`. */
export async function findInstalledService(
	dataDir: string,
	options: { home?: string; systemRoot?: string } = {},
): Promise<InstalledService | undefined> {
	const wanted = resolve(dataDir);
	const candidates: Array<{ scope: ServiceScope; unitPath: string }> = [
		{ scope: "user", unitPath: userServiceUnitPath(options.home) },
		{ scope: "system", unitPath: systemServiceUnitPath(options.systemRoot) },
	];
	for (const candidate of candidates) {
		const text = await readExisting(candidate.unitPath).catch(() => undefined);
		if (text === undefined || !isGeneratedUnit(text)) continue;
		const metadata = parseUnitMetadata(text);
		if (metadata.dataDir && resolve(metadata.dataDir) === wanted) {
			return { ...candidate, metadata };
		}
	}
	return undefined;
}

export function serviceScopeFromEnv(env: NodeJS.ProcessEnv = process.env): ServiceScope | undefined {
	const value = env["PIXIP_SERVICE"];
	return value === "user" || value === "system" ? value : undefined;
}

export interface RestartDecision {
	mode: "systemd" | "detached";
	scope?: ServiceScope;
}

/** Decide whether restart must go through systemd instead of a detached helper. */
export function restartDecision(env: NodeJS.ProcessEnv, serviceScope?: ServiceScope): RestartDecision {
	const scope = serviceScopeFromEnv(env) ?? serviceScope;
	return scope ? { mode: "systemd", scope } : { mode: "detached" };
}

/** Is `pid` the main process systemd reports for the unit? */
export async function serviceOwnsPid(scope: ServiceScope, pid: number, runner: CommandRunner): Promise<boolean> {
	const result = await runner.run("systemctl", systemctlArgs(scope, "show", "-p", "MainPID", "--value", SERVICE_UNIT));
	if (result.code !== 0) return false;
	return Number(result.stdout.trim()) === pid;
}
